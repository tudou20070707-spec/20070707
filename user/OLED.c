/* ===================================================================
 *                SSD1306 OLED 显示屏驱动文件
 * ===================================================================
 * 本文件实现通过 STM32F103 的 I2C1 硬件外设驱动 0.96 寸 OLED 屏。
 *
 * 【I2C 总线共享架构】
 *   I2C1 总线上挂载两个从设备:
 *     MPU6050  — 设备地址 0xD0, 用于读取加速度/陀螺仪数据
 *     SSD1306  — 设备地址 0x78, 用于驱动 OLED 显示
 *   主机通过不同的设备地址区分与谁通信，互不干扰。
 *
 * 【SSD1306 与 MPU6050 通信方式的重要区别】
 *   MPU6050:
 *     发完设备地址后，第二字节是"寄存器地址"（如 0x3B）
 *     因为 MPU6050 内部有上百个寄存器，需要地址来定位。
 *
 *   SSD1306 (OLED):
 *     发完设备地址后，紧跟的是"控制字节"（0x00=命令, 0x40=数据）
 *     而不是寄存器地址！SSD1306 内部没有"寄存器地址"这个概念，
 *     它靠控制字节来区分: 接下来的字节是命令还是显示数据。
 *
 *   类比: MPU6050 是"按房间号存取"（寄存器地址），
 *         SSD1306 是"你说命令还是数据就行"（控制字节）。
 *
 * 【SSD1306 显示原理】
 *   芯片内部有一块 GDDRAM (Graphic Display Data RAM)，共 128×64 = 1024 字节
 *   每个 bit 对应屏幕上一个像素点: 1 = 亮, 0 = 灭
 *
 *   GDDRAM 按"页"组织:
 *     Page 0: 第 0~7   行像素 (对应 Y 坐标 0~7)
 *     Page 1: 第 8~15  行像素
 *     ...
 *     Page 7: 第 56~63 行像素
 *
 *   同一页内，列地址 0~127 对应 X 坐标的 128 列
 *
 *   写入一页的一列 = 1 字节 = 控制该列竖直方向 8 个像素的亮灭
 *   每个字节的 bit0 在最上面, bit7 在最下面:
 *
 *         列地址 0    列地址 1    ...  列地址 127
 *       ┌──────────┬──────────┬─────┬──────────┐
 *       │  bit0    │          │     │          │  ← Y=0
 *       │  bit1    │          │     │          │  ← Y=1
 *   P0  │  ...     │  一个字  │     │          │
 *       │  bit7    │  节搞定  │     │          │  ← Y=7
 *       ├──────────┼──────────┼─────┼──────────┤
 *   P1  │          │          │     │          │  ← Y=8~15
 *       ├──────────┼──────────┼─────┼──────────┤
 *   ...
 *       ├──────────┼──────────┼─────┼──────────┤
 *   P7  │          │          │     │          │  ← Y=56~63
 *       └──────────┴──────────┴─────┴──────────┘
 *
 * =================================================================== */

