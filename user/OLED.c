/* ============================================================
 * 显示缓冲区 (1024 字节 = 128列 × 8页)
 * ------------------------------------------------------------
 * 【为什么需要缓冲区？】
 *   如果每次写字符都直接发 I2C 到 OLED，屏幕会逐行刷新，
 *   肉眼能看到明显的闪烁和撕裂。
 *
 *   使用缓冲区后:
 *     1. 所有绘制函数 (ShowChar, Clear 等) 只修改缓冲区 (SRAM)
 *     2. 调用 OLED_Refresh() 时，一次性把 1024 字节推到 OLED
 *     3. 屏幕更新在 ~10ms 内完成，肉眼看不到闪烁
 *
 * 【缓冲区布局】
 *   OLED_Buffer[page][col]
 *     page: 0~7  (8 页, 每页高 8 像素)
 *     col:  0~127 (128 列)
 *     每个字节的 8 个 bit 对应该列 8 个像素的亮灭
 *
 * 【内存开销】
 *   128 × 8 = 1024 字节
 *   STM32F103C8T6 有 20KB SRAM，完全够用 (仅占 5%)
 * ============================================================ */
static uint8_t OLED_Buffer[OLED_PAGES][OLED_WIDTH];

