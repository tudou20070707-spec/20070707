#ifndef __MPU9250_H
#define __MPU9250_H

#include "stm32f10x.h"                  // Device header

/* ============================================================
 * MPU9250 器件地址 (I2C 7位地址)
 * ------------------------------------------------------------
 * AD0 引脚接 GND  → MPU9250 地址为 0x68
 * AD0 引脚接 VCC  → MPU9250 地址为 0x69
 * 左移一位得到写入地址: 0xD0 / 0xD2
 * ============================================================ */
#define MPU9250_ADDR_WRITE  0xD0        // 写地址 (0x68 << 1 | 0)
#define MPU9250_ADDR_READ   0xD1        // 读地址 (0x68 << 1 | 1)

/* ============================================================
 * AK8963 磁力计 I2C 地址 (7位地址 = 0x0C)
 * ------------------------------------------------------------
 * MPU9250 内部集成了 AK8963 磁力计，挂载在辅助 I2C 总线上。
 * 需要先启用 MPU9250 的 Bypass 模式才能直接访问磁力计。
 * ============================================================ */
#define AK8963_ADDR_WRITE   0x18        // 磁力计写地址 (0x0C << 1 | 0)
#define AK8963_ADDR_READ    0x19        // 磁力计读地址 (0x0C << 1 | 1)

/* ============================================================
 * MPU9250 器件 ID
 * ============================================================ */
#define MPU9250_WHO_AM_I_VAL  0x71      // MPU9250 WHO_AM_I 寄存器默认值
#define AK8963_WHO_AM_I_VAL   0x48      // AK8963 WIA 寄存器默认值

/* ============================================================
 * MPU9250 内部寄存器地址定义 (加速度+陀螺仪部分，兼容MPU6050)
 * 参考 MPU-9250 Register Map
 * ============================================================ */

/* --- 基本配置寄存器 --- */
#define MPU9250_SMPLRT_DIV      0x19    // 采样率分频器
                                        // 采样率 = 陀螺仪输出率 / (1 + SMPLRT_DIV)
                                        // 例如: 1kHz / (1+4) = 200Hz

#define MPU9250_CONFIG           0x1A    // 配置寄存器
                                        // [7:3] 保留
                                        // [2:0] DLPF_CFG: 数字低通滤波器配置
                                        //   0: 带宽 260Hz (延迟 0ms)
                                        //   1: 带宽 184Hz (延迟 2.0ms)
                                        //   6: 带宽 5Hz   (延迟 19.0ms)

#define MPU9250_GYRO_CONFIG      0x1B    // 陀螺仪配置寄存器
                                        // [4:3] FS_SEL: 量程选择
                                        //   0: ±250  °/s
                                        //   1: ±500  °/s
                                        //   2: ±1000 °/s
                                        //   3: ±2000 °/s

#define MPU9250_ACCEL_CONFIG     0x1C    // 加速度计配置寄存器
                                        // [4:3] AFS_SEL: 量程选择
                                        //   0: ±2g
                                        //   1: ±4g
                                        //   2: ±8g
                                        //   3: ±16g

/* --- MPU9250 特有寄存器 --- */
#define MPU9250_INT_PIN_CFG      0x37    // 中断/旁路配置寄存器
                                        // [1] BYPASS_EN: 旁路模式使能
                                        //   1 = 辅助 I2C 总线直接连接到主 I2C 总线
                                        //       使主机能直接访问 AK8963 磁力计

#define MPU9250_USER_CTRL        0x6A    // 用户控制寄存器
                                        // [5] I2C_MST_EN: I2C 主模式使能
                                        // [4] I2C_IF_DIS: 从 I2C 模式禁用

/* --- 数据输出寄存器 (从高字节开始) --- */
#define MPU9250_ACCEL_XOUT_H     0x3B    // 加速度 X 轴高字节
#define MPU9250_ACCEL_XOUT_L     0x3C    // 加速度 X 轴低字节
#define MPU9250_ACCEL_YOUT_H     0x3D    // 加速度 Y 轴高字节
#define MPU9250_ACCEL_YOUT_L     0x3E    // 加速度 Y 轴低字节
#define MPU9250_ACCEL_ZOUT_H     0x3F    // 加速度 Z 轴高字节
#define MPU9250_ACCEL_ZOUT_L     0x40    // 加速度 Z 轴低字节

#define MPU9250_TEMP_OUT_H       0x41    // 温度传感器高字节
#define MPU9250_TEMP_OUT_L       0x42    // 温度传感器低字节

#define MPU9250_GYRO_XOUT_H      0x43    // 陀螺仪 X 轴高字节
#define MPU9250_GYRO_XOUT_L      0x44    // 陀螺仪 X 轴低字节
#define MPU9250_GYRO_YOUT_H      0x45    // 陀螺仪 Y 轴高字节
#define MPU9250_GYRO_YOUT_L      0x46    // 陀螺仪 Y 轴低字节
#define MPU9250_GYRO_ZOUT_H      0x47    // 陀螺仪 Z 轴高字节
#define MPU9250_GYRO_ZOUT_L      0x48    // 陀螺仪 Z 轴低字节

/* --- 电源管理寄存器 --- */
#define MPU9250_PWR_MGMT_1       0x6B    // 电源管理寄存器1
                                        // [6] SLEEP: 睡眠模式 (1=睡眠, 0=唤醒)
                                        // [3] TEMP_DIS: 禁用温度传感器
                                        // [2:0] CLKSEL: 时钟源选择
                                        //   0: 内部 8MHz RC 振荡器
                                        //   1: X 轴陀螺仪参考时钟 (PLL)

#define MPU9250_PWR_MGMT_2       0x6C    // 电源管理寄存器2
                                        // 控制各轴的待机模式

#define MPU9250_WHO_AM_I         0x75    // 器件 ID 寄存器
                                        // MPU9250 复位后默认值为 0x71

/* ============================================================
 * AK8963 磁力计内部寄存器地址
 * ============================================================ */
#define AK8963_WIA               0x00    // 器件 ID (默认 0x48)
#define AK8963_INFO              0x01    // 信息寄存器
#define AK8963_ST1               0x02    // 状态寄存器1 (DRDY: 数据就绪)
#define AK8963_HXL               0x03    // X 轴低字节
#define AK8963_HXH               0x04    // X 轴高字节
#define AK8963_HYL               0x05    // Y 轴低字节
#define AK8963_HYH               0x06    // Y 轴高字节
#define AK8963_HZL               0x07    // Z 轴低字节
#define AK8963_HZH               0x08    // Z 轴高字节
#define AK8963_ST2               0x09    // 状态寄存器2 (HOFL: 溢出标志)
#define AK8963_CNTL1             0x0A    // 控制寄存器1
                                        // [3:0] MODE:
                                        //   0x00: 掉电模式
                                        //   0x01: 单次测量
                                        //   0x02: 连续测量 8Hz
                                        //   0x04: 外部触发
                                        //   0x06: 连续测量 100Hz
                                        // [4] BIT: 输出位宽 (0=14位, 1=16位)
#define AK8963_CNTL2             0x0B    // 控制寄存器2 (复位)
#define AK8963_ASTC              0x0C    // 自检控制
#define AK8963_ASAX              0x10    // X 轴灵敏度校准
#define AK8963_ASAY              0x11    // Y 轴灵敏度校准
#define AK8963_ASAZ              0x12    // Z 轴灵敏度校准

/* ============================================================
 * 读取到的原始数据结构体
 * 包含 3 轴加速度 + 1 路温度 + 3 轴陀螺仪 + 3 轴磁力计
 * ============================================================ */
typedef struct
{
    int16_t Accel_X;                    // 加速度 X 轴原始值
    int16_t Accel_Y;                    // 加速度 Y 轴原始值
    int16_t Accel_Z;                    // 加速度 Z 轴原始值
    int16_t Temperature;                // 温度原始值
    int16_t Gyro_X;                     // 陀螺仪 X 轴原始值
    int16_t Gyro_Y;                     // 陀螺仪 Y 轴原始值
    int16_t Gyro_Z;                     // 陀螺仪 Z 轴原始值
    int16_t Mag_X;                      // 磁力计 X 轴原始值
    int16_t Mag_Y;                      // 磁力计 Y 轴原始值
    int16_t Mag_Z;                      // 磁力计 Z 轴原始值
} MPU9250_Data;

/* ============================================================
 * 姿态角度结构体（经滤波融合后的稳定角度）
 * ============================================================ */
typedef struct
{
    float Roll;                         // 横滚角 (°)，绕 X 轴旋转
    float Pitch;                        // 俯仰角 (°)，绕 Y 轴旋转
    float Yaw;                          // 偏航角 (°)，绕 Z 轴旋转（磁力计修正后，不漂移）
} MPU9250_Angle;

/* ============================================================
 * 滤波参数宏定义（可根据实际使用场景调整）
 * ------------------------------------------------------------
 * 陀螺仪量程: ±250 °/s, 灵敏度 131 LSB/°/s
 * 加速度计量程: ±2g, 灵敏度 16384 LSB/g
 * 磁力计量程: ±4800 μT, 灵敏度 0.6 μT/LSB (16位模式)
 * ============================================================ */

/* --- 死区阈值 --- */
/*
 * 角速度在此范围内视为静止，直接置零
 * 2 LSB ≈ 0.015 °/s，对应几乎没有转动的情况
 * 如果小车震动大可以适当增大（如 5~10）
 */
#define GYRO_DEADZONE       2
/*
 * Yaw 轴现在有磁力计修正（MPU9250 新特性），不再会无限漂移
 * 所以 Z 轴死区不需要像 MPU6050 那样设得很大
 * 5 LSB ≈ 0.04 °/s，挡住校准后的微小偏差即可
 */
#define GYRO_DEADZONE_YAW   5

/* --- 低通滤波系数 --- */
/*
 * α 越小滤波越强，但响应也越慢
 * filtered = filtered_old + α × (raw - filtered_old)
 *
 * α = 0.2 → 适中滤波，适合手持/慢速姿态检测
 * α = 0.5 → 轻度滤波，响应快但噪声多
 * α = 0.1 → 强滤波，适合震动环境但延迟大
 */
#define LPF_ALPHA_GYRO      0.80f   // 陀螺仪低通系数（0.8 = 急停不拖尾，噪声稍大）
#define LPF_ALPHA_ACCEL     0.15f   // 加速度计低通系数（可以更强一些）
#define LPF_ALPHA_MAG       0.30f   // 磁力计低通系数

/* --- 互补滤波系数 --- */
/*
 * 陀螺仪: 短期精准但积分会漂移
 * 加速度计: 长期准确但瞬间噪声大
 * 磁力计: 无漂移但易受环境干扰
 * 互补滤波 = 陀螺仪积分 × 0.98 + 加速度角度 × 0.02
 *
 * COMP_TAU 越大越信任陀螺仪，越小越信任加速度计
 */
#define COMP_GYRO_TRUST     0.98f   // 陀螺仪权重（0~1）

/* --- 磁力计 Yaw 修正系数 --- */
/*
 * 磁力计修正 Yaw 的权重（0~1）
 * 0.03 = 每周期用磁力计修正 3%，约 3 秒收敛
 * 调大 → 更快收敛但容易受磁场干扰影响
 * 调小 → 抗干扰强但收敛慢
 */
#define MAG_YAW_CORRECT     0.03f

/* --- 静止检测阈值 --- */
/*
 * 加速度变化量小于此值时认为设备静止，可重新校准零偏
 * 2000 LSB ≈ 0.12g @ ±2g 量程
 */
#define STATIONARY_THRESH   2000

/* ============================================================
 * 函数声明
 * ============================================================ */
void     I2C_MyInit(void);                                          // I2C1 硬件初始化（MPU9250 和 OLED 共用）
void     MPU9250_Init(void);                                        // 初始化 MPU9250（I2C + 唤醒 + 磁力计）
uint8_t  MPU9250_ReadID(void);                                      // 读取 WHO_AM_I 寄存器，返回器件 ID
uint8_t  MPU9250_ReadMagID(void);                                   // 读取磁力计 WIA 寄存器，返回器件 ID
void     MPU9250_ReadData(MPU9250_Data *pData);                     // 读取全部传感器数据（加速度+温度+陀螺仪+磁力计）
void     MPU9250_ReadAccel(int16_t *ax, int16_t *ay, int16_t *az);  // 仅读取加速度
void     MPU9250_ReadGyro(int16_t *gx, int16_t *gy, int16_t *gz);   // 仅读取陀螺仪
void     MPU9250_ReadMag(int16_t *mx, int16_t *my, int16_t *mz);    // 仅读取磁力计

/* --- 校准与姿态解算 --- */
void     MPU9250_Calibrate(void);                                    // 上电静止校准（计算陀螺仪零偏 + 磁力计初始偏航）
void     MPU9250_GetAngle(MPU9250_Angle *pAngle);                    // 获取滤波融合后的 Roll/Pitch/Yaw 角度
uint8_t  MPU9250_IsStationary(void);                                 // 检测设备是否处于静止状态

#endif
