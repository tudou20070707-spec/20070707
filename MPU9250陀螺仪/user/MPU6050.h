#ifndef __MPU6050_H
#define __MPU6050_H

#include "stm32f10x.h"                  // Device header

/* ============================================================
 * MPU6050 器件地址 (I2C 7位地址)
 * ------------------------------------------------------------
 * AD0 引脚接 GND  → 地址为 0x68
 * AD0 引脚接 VCC  → 地址为 0x69
 * 左移一位得到写入地址: 0xD0 / 0xD2
 * ============================================================ */
#define MPU6050_ADDR_WRITE  0xD0        // 写地址 (0x68 << 1 | 0)
#define MPU6050_ADDR_READ   0xD1        // 读地址 (0x68 << 1 | 1)

/* ============================================================
 * MPU6050 内部寄存器地址定义
 * 参考 MPU-6000/MPU-6050 Register Map
 * ============================================================ */

/* --- 基本配置寄存器 --- */
#define MPU6050_SMPLRT_DIV      0x19    // 采样率分频器
                                        // 采样率 = 陀螺仪输出率 / (1 + SMPLRT_DIV)
                                        // 例如: 1kHz / (1+4) = 200Hz

#define MPU6050_CONFIG           0x1A    // 配置寄存器
                                        // [7:3] 保留
                                        // [2:0] DLPF_CFG: 数字低通滤波器配置
                                        //   0: 带宽 260Hz (延迟 0ms)
                                        //   1: 带宽 184Hz (延迟 2.0ms)
                                        //   6: 带宽 5Hz   (延迟 19.0ms)

#define MPU6050_GYRO_CONFIG      0x1B    // 陀螺仪配置寄存器
                                        // [4:3] FS_SEL: 量程选择
                                        //   0: ±250  °/s
                                        //   1: ±500  °/s
                                        //   2: ±1000 °/s
                                        //   3: ±2000 °/s

#define MPU6050_ACCEL_CONFIG     0x1C    // 加速度计配置寄存器
                                        // [4:3] AFS_SEL: 量程选择
                                        //   0: ±2g
                                        //   1: ±4g
                                        //   2: ±8g
                                        //   3: ±16g

/* --- 数据输出寄存器 (从高字节开始) --- */
#define MPU6050_ACCEL_XOUT_H     0x3B    // 加速度 X 轴高字节
#define MPU6050_ACCEL_XOUT_L     0x3C    // 加速度 X 轴低字节
#define MPU6050_ACCEL_YOUT_H     0x3D    // 加速度 Y 轴高字节
#define MPU6050_ACCEL_YOUT_L     0x3E    // 加速度 Y 轴低字节
#define MPU6050_ACCEL_ZOUT_H     0x3F    // 加速度 Z 轴高字节
#define MPU6050_ACCEL_ZOUT_L     0x40    // 加速度 Z 轴低字节

#define MPU6050_TEMP_OUT_H       0x41    // 温度传感器高字节
#define MPU6050_TEMP_OUT_L       0x42    // 温度传感器低字节

#define MPU6050_GYRO_XOUT_H      0x43    // 陀螺仪 X 轴高字节
#define MPU6050_GYRO_XOUT_L      0x44    // 陀螺仪 X 轴低字节
#define MPU6050_GYRO_YOUT_H      0x45    // 陀螺仪 Y 轴高字节
#define MPU6050_GYRO_YOUT_L      0x46    // 陀螺仪 Y 轴低字节
#define MPU6050_GYRO_ZOUT_H      0x47    // 陀螺仪 Z 轴高字节
#define MPU6050_GYRO_ZOUT_L      0x48    // 陀螺仪 Z 轴低字节

/* --- 电源管理寄存器 --- */
#define MPU6050_PWR_MGMT_1       0x6B    // 电源管理寄存器1
                                        // [6] SLEEP: 睡眠模式 (1=睡眠, 0=唤醒)
                                        // [3] TEMP_DIS: 禁用温度传感器
                                        // [2:0] CLKSEL: 时钟源选择
                                        //   0: 内部 8MHz RC 振荡器
                                        //   1: X 轴陀螺仪参考时钟 (PLL)

#define MPU6050_PWR_MGMT_2       0x6C    // 电源管理寄存器2
                                        // 控制各轴的待机模式

#define MPU6050_WHO_AM_I         0x75    // 器件 ID 寄存器
                                        // 复位后默认值为 0x68
                                        // 用于验证 I2C 通信是否正常

/* ============================================================
 * 读取到的原始数据结构体
 * 包含 3 轴加速度 + 1 路温度 + 3 轴陀螺仪
 * ============================================================ */
typedef struct
{
    int16_t Accel_X;                    // 加速度 X 轴原始值
    int16_t Accel_Y;                    // 加速度 Y 轴原始值
    int16_t Accel_Z;                    // 加速度 Z 轴原始值
    int16_t Temperature;                // 温度原始值
    int16_t Gyro_X;                     // 陀螺仪 X 轴原始值
    int16_t Gyro_Y;                     // 陀螺仪 Y 轴原始值
    int16_t Gyro_Z;                     // 陀螺仪 Z 轴原始值
} MPU6050_Data;

/* ============================================================
 * 姿态角度结构体（经滤波融合后的稳定角度）
 * ============================================================ */
typedef struct
{
    float Roll;                         // 横滚角 (°)，绕 X 轴旋转
    float Pitch;                        // 俯仰角 (°)，绕 Y 轴旋转
    float Yaw;                          // 偏航角 (°)，绕 Z 轴旋转（仅陀螺仪积分，会漂移）
} MPU6050_Angle;

/* ============================================================
 * 滤波参数宏定义（可根据实际使用场景调整）
 * ------------------------------------------------------------
 * 陀螺仪量程: ±250 °/s, 灵敏度 131 LSB/°/s
 * ============================================================ */

/* --- 死区阈值 --- */
/*
 * 角速度在此范围内视为静止，直接置零
 * 2 LSB ≈ 0.015 °/s，对应几乎没有转动的情况
 * 如果小车震动大可以适当增大（如 5~10）
 */
#define GYRO_DEADZONE       2
/*
 * Yaw 轴没有加速度计修正，残余零偏会一直积分导致漂移
 * 所以 Z 轴死区需要设大一些，挡住校准后残留的微小偏差
 * 15 LSB ≈ 0.11 °/s (15 / 131)，不影响正常转弯检测
 * 如果你看到 Yaw 还在漂，继续调大这个值 (最大到 30)
 */
#define GYRO_DEADZONE_YAW   15

/* --- 低通滤波系数 --- */
/*
 * α 越小滤波越强，但响应也越慢
 * filtered = filtered_old + α × (raw - filtered_old)
 *
 * α = 0.2 → 适中滤波，适合手持/慢速姿态检测
 * α = 0.5 → 轻度滤波，响应快但噪声多
 * α = 0.1 → 强滤波，适合震动环境但延迟大
 */
#define LPF_ALPHA_GYRO      0.80f   // 陀螺仪低通系数（0.8 = 急停不拖尾，噪声稍大）
#define LPF_ALPHA_ACCEL     0.15f   // 加速度计低通系数（可以更强一些）

/* --- 互补滤波系数 --- */
/*
 * 陀螺仪: 短期精准但积分会漂移
 * 加速度计: 长期准确但瞬间噪声大
 * 互补滤波 = 陀螺仪积分 × 0.98 + 加速度角度 × 0.02
 *
 * COMP_TAU 越大越信任陀螺仪，越小越信任加速度计
 */
#define COMP_GYRO_TRUST     0.98f   // 陀螺仪权重（0~1）

/* --- 静止检测阈值 --- */
/*
 * 加速度变化量小于此值时认为设备静止，可重新校准零偏
 * 2000 LSB ≈ 0.12g @ ±2g 量程
 */
#define STATIONARY_THRESH   2000

/* ============================================================
 * 函数声明
 * ============================================================ */
void     I2C_MyInit(void);                              // I2C1 硬件初始化（MPU6050 和 OLED 共用）
void     MPU6050_Init(void);                        // 初始化 MPU6050（配置 I2C + 唤醒芯片）
uint8_t  MPU6050_ReadID(void);                      // 读取 WHO_AM_I 寄存器，返回器件 ID
void     MPU6050_ReadData(MPU6050_Data *pData);     // 读取全部传感器数据（加速度+温度+陀螺仪）
void     MPU6050_ReadAccel(int16_t *ax, int16_t *ay, int16_t *az);   // 仅读取加速度
void     MPU6050_ReadGyro(int16_t *gx, int16_t *gy, int16_t *gz);     // 仅读取陀螺仪

/* --- 校准与姿态解算 --- */
void     MPU6050_Calibrate(void);                                     // 上电静止校准（计算陀螺仪零偏）
void     MPU6050_GetAngle(MPU6050_Angle *pAngle);                     // 获取滤波融合后的 Roll/Pitch/Yaw 角度
uint8_t  MPU6050_IsStationary(void);                                  // 检测设备是否处于静止状态

#endif
