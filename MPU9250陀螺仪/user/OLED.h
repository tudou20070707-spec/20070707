#ifndef __OLED_H
#define __OLED_H

#include "stm32f10x.h"                  // Device header
#include "MPU6050.h"                    // 需要 MPU6050_Data 结构体定义

/* ============================================================
 *               SSD1306 OLED 显示屏驱动 — 头文件
 * ============================================================
 * 适用屏幕: 0.96 寸 128x64 像素 I2C 接口 OLED
 * 驱动芯片: SSD1306
 * 接口:     I2C1（与 MPU6050 共用同一总线）
 *
 * 【I2C 总线共享说明】
 *   MPU6050  设备地址: 0xD0 (写) / 0xD1 (读)
 *   OLED     设备地址: 0x78 (写) / 0x79 (读)
 *   两者挂在同一条 I2C1 总线上，通过不同的设备地址区分。
 *
 * 【硬件连接 (I2C1)】
 *   PB6 → OLED SCL  (I2C1_SCL)
 *   PB7 → OLED SDA  (I2C1_SDA)
 *   与 MPU6050 共用 SCL/SDA，需外接 4.7kΩ 上拉电阻
 *
 * 【SSD1306 显示组织结构】
 *   屏幕分为 8 个"页" (Page 0~7)，每页高 8 像素
 *   列地址 0~127，共 128 列
 *   总像素 = 8 页 × 128 列 × 8 位高 = 128 × 64 像素
 *
 *   使用 8×16 字体时:
 *     - 每页对应该字符的上半部分或下半部分
 *     - 一个字符占 2 页（高 16 像素）
 *     - 屏幕最多显示 4 行文字（8页 ÷ 2 = 4行）
 *     - 每行最多 16 个字符（128列 ÷ 8 = 16个）
 * ============================================================ */

/* ============================================================
 * OLED 设备地址 (I2C 7位地址)
 * ------------------------------------------------------------
 * SSD1306 的 7 位地址固定为 0x3C
 * 左移一位后: 写地址 = 0x78, 读地址 = 0x79
 * 注意: 某些 OLED 模块背面电阻可切换为 0x3D → 0x7A/0x7B
 * ============================================================ */
#define OLED_ADDR_WRITE     0x78            // OLED 写地址 (0x3C << 1 | 0)
#define OLED_ADDR_READ      0x79            // OLED 读地址 (0x3C << 1 | 1)

/* ============================================================
 * SSD1306 控制字节定义
 * ------------------------------------------------------------
 * I2C 发送给 SSD1306 的第一个字节不是寄存器地址，
 * 而是控制字节 (Control Byte)，用来区分后续字节是命令还是数据:
 *
 *   Co (bit7): 连续位
 *     0 = 最后一个控制字节之后还有数据字节
 *     1 = 接下来全是数据/命令字节
 *   D/C# (bit6): 数据/命令选择
 *     0 = 后续字节是【命令】
 *     1 = 后续字节是【数据】(写入 GDDRAM 显示缓冲区)
 *   bit[5:0]: 保留，填 0
 *
 * 我们简化处理: 每次发控制字节后只跟一种类型，
 * 所以 Co=0 (后面还有), D/C# 区分命令还是数据
 * ============================================================ */
#define OLED_CTRL_CMD       0x00            // 控制字节: 后面是命令
#define OLED_CTRL_DATA      0x40            // 控制字节: 后面是数据

/* ============================================================
 * 显示参数
 * ============================================================ */
#define OLED_WIDTH          128             // 屏幕宽度 (像素)
#define OLED_HEIGHT         64              // 屏幕高度 (像素)
#define OLED_PAGES          8               // 页数 (每页 8 像素高)
#define OLED_CHAR_WIDTH     8               // 字符宽度 (8×16 字体)
#define OLED_CHAR_HEIGHT    16              // 字符高度 (8×16 字体)
#define OLED_MAX_COL        16              // 每行最大字符数 (128÷8)
#define OLED_MAX_ROW        4               // 最大行数 (64÷16)

/* ============================================================
 * 函数声明
 * ============================================================ */
void OLED_Init(void);                                           // 初始化 OLED（I2C 必须已初始化）
void OLED_Clear(void);                                          // 清屏（全黑，只清缓冲区）
void OLED_Refresh(void);                                        // 刷新屏幕（将缓冲区一次性推送到 OLED）
void OLED_ClearLine(uint8_t row);                               // 清除指定行
void OLED_ShowChar(uint8_t row, uint8_t col, char ch);          // 在指定行列显示一个字符
void OLED_ShowString(uint8_t row, uint8_t col, const char *str);// 在指定行列显示字符串
void OLED_ShowInt(uint8_t row, uint8_t col, int16_t num);       // 在指定行列显示有符号整数
void OLED_ShowFloat(uint8_t row, uint8_t col, float num);       // 在指定行列显示浮点数 (±XXX.X)
void OLED_ShowMPU6050(MPU6050_Data *pData);                     // 显示 MPU6050 全部传感器数据

#endif
